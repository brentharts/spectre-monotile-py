"""Stage B1b: dissections tau*T = union of ABCK tiles, found by exact cover (not copied from the paper), in the doubled coordinates of Z^6.
Run: python3 t9_dissect.py     -> dissections.json
Points are x in (1/2)Z^6 stored as integer 2x; physical p = Epar x, internal (conjugate) q = Eperp x, star s = tau q.
The icosahedral group acts on x as signed permutations (checked)."""
import itertools, json, sys, time
import numpy as np
tau = (1 + 5 ** .5) / 2; tc = 1 - tau
Ep = np.array([[0, 1, tau], [0, -1, tau], [1, tau, 0], [-1, tau, 0], [tau, 0, 1], [tau, 0, -1]]).T
Eq = np.array([[0, 1, tc], [0, -1, tc], [1, tc, 0], [-1, tc, 0], [tc, 0, 1], [tc, 0, -1]]).T
A = np.vstack([Ep, Eq]); Ai = np.linalg.inv(A)
def conj_entry(r):
    for a2 in range(-8, 9):
        for b2 in range(-8, 9):
            if abs((a2 + b2 * tau) / 2 - r) < 1e-9: return (a2 + b2 * tc) / 2
    raise ValueError(r)
# --- the group (120 elements) as 3x3 matrices, closure of generators
def rot(u, th):
    u = np.array(u, float); u /= np.linalg.norm(u); K = np.array([[0, -u[2], u[1]], [u[2], 0, -u[0]], [-u[1], u[0], 0]])
    return np.eye(3) + np.sin(th) * K + (1 - np.cos(th)) * K @ K
gens = [rot((0, 1, tau), 2 * np.pi / 5), np.array([[0, 1, 0], [0, 0, 1], [1, 0, 0]], float), np.diag([-1., -1, 1]), -np.eye(3)]
G = [np.eye(3)]
key = lambda M: tuple(np.round(M, 6).flatten())
seen = {key(G[0])}
frontier = [G[0]]
while frontier:
    new = []
    for M in frontier:
        for g in gens:
            N = g @ M
            if key(N) not in seen: seen.add(key(N)); G.append(N); new.append(N)
    frontier = new
assert len(G) == 120, len(G)
RX = []                                   # action on x (6x6 integer signed permutations)
for R in G:
    Rc = np.vectorize(conj_entry)(R)
    M = Ai @ np.block([[R, np.zeros((3, 3))], [np.zeros((3, 3)), Rc]]) @ A
    assert np.allclose(M, np.rint(M), atol=1e-9) and np.allclose(np.abs(M).sum(0), 1), "not a signed permutation"
    RX.append(np.rint(M).astype(int))
S = Ai @ np.block([[tau * np.eye(3), np.zeros((3, 3))], [np.zeros((3, 3)), tc * np.eye(3)]]) @ A   # inflation on x (entries +-1/2)
assert np.allclose(np.abs(S), 0.5)
phys = lambda x2: (Ep @ (x2 / 2.0)); star = lambda x2: tau * (Eq @ (x2 / 2.0))
def xof(p):
    p = np.array(p, float); pc = np.array([conj_entry(r) if False else 0 for r in p])
    return None

h = 0.5
TILES = {   # vertices as x (units of 1/2 allowed), origin first; from the exact solve of Table 1 (STAGE_B1 item 6)
    "A": [(0,) * 6, (h, h, h, -h, 1.5, h), (1, 0, 1, 0, 1, 0), (h, -h, h, -h, h, h)],
    "B": [(0,) * 6, (h, h, h, -h, 1.5, h), (1, 0, 1, 0, 1, 0), (0, 0, 1, 0, 1, 0)],
    "C": [(0,) * 6, (0, 0, 0, 0, 0, -1), (1, 0, 1, 0, 1, 0), (h, -h, h, h, h, -h)],
    "K": [(0,) * 6, (0, 0, 0, 1, 0, 0), (h, h, h, h, h, h), (0, h, 0, h, 0, 0)],
}
D = 4          # we store 4x
T4 = {k: np.rint(np.array(v) * D).astype(int) for k, v in TILES.items()}
def verify_tiles():
    t = (1 + 5 ** .5) / 2
    ref = {"K": [(0, 0, 0), (-1, t, 0), (t, t, t), (-.5, .5 / t, .5 * t)], "A": [(0, 0, 0), (t ** 3, 0, t ** 2), (t ** 2, t ** 2, t ** 2), (t ** 2, 1, 0)]}
    for k in ref:
        for xv, pv in zip(T4[k], ref[k]): assert np.allclose(Ep @ (xv / D), pv, atol=1e-9), (k, xv, pv)
verify_tiles()
def phys4(x4): return Ep @ (np.asarray(x4) / D)
def star4(x4): return tau * (Eq @ (np.asarray(x4) / D))
# lattice generated by all images of all tile vertices
import sympy
vecs = {tuple(int(z) for z in RX[i] @ v) for i in range(120) for k in T4 for v in T4[k]}
Hn = sympy.Matrix([list(v) for v in vecs]).T
from sympy.matrices.normalforms import smith_normal_form
G6 = sympy.Matrix(sorted(vecs)).T
snf = smith_normal_form(G6, domain=sympy.ZZ)
print("module generated by the images of tile vertices: rank", np.linalg.matrix_rank(np.array(G6.tolist(), float)), "Smith diagonal", [snf[i, i] for i in range(6)])
S4 = lambda x4: np.rint(S @ np.asarray(x4) ).astype(int) if np.allclose(S @ np.asarray(x4), np.rint(S @ np.asarray(x4)), atol=1e-9) else None
bad = [(k, i) for k in T4 for i, v in enumerate(T4[k]) if S4(v) is None]
print("S(tile vertex) integral in 4x-coordinates for all tiles:", not bad, bad[:3])

# ---------------------------------------------------------------- dissection by exact cover
EDGES = set()
for k in T4:
    for i in range(4):
        for j in range(4):
            if i != j:
                d = T4[k][j] - T4[k][i]
                for g in range(120): EDGES.add(tuple(int(z) for z in RX[g] @ d))
EDGES = np.array(sorted(EDGES)); print("distinct edge vectors (4x coordinates):", len(EDGES))
def bary(P, V):                       # barycentric coordinates of points P (n,3) in tetrahedron V (4,3)
    Mx = (V[1:] - V[0]).T; l = np.linalg.solve(Mx, (P - V[0]).T).T
    return np.hstack([1 - l.sum(1, keepdims=True), l])
def dissect(name, Qmax=9.0, nsamp=400, seed=1, verbose=True):
    V4 = np.array([S4(v) for v in T4[name]]); V = np.array([phys4(v) for v in V4])
    c0 = star4(V4[0]); tol = 1e-9
    inside = lambda x4: bool((bary(phys4(x4)[None, :], V) > -tol).all()) and np.linalg.norm(star4(x4) - c0) <= Qmax
    pts = {tuple(v) for v in V4}; frontier = list(pts); t0 = time.time()
    while frontier:
        new = []
        for p in frontier:
            cand = EDGES + np.array(p)
            ph = (cand / D) @ Ep.T; b = bary(ph, V); ok = (b > -tol).all(1)
            stt = np.linalg.norm(tau * ((cand / D) @ Eq.T) - c0, axis=1) <= Qmax
            for q in cand[ok & stt]:
                tq = tuple(int(z) for z in q)
                if tq not in pts: pts.add(tq); new.append(tq)
        frontier = new
    pts = sorted(pts); idx = {p: i for i, p in enumerate(pts)}
    if verbose: print(name, "points reachable inside tau*T:", len(pts), "%.0fs" % (time.time() - t0), flush=True)
    rng = np.random.default_rng(seed)
    # sample points in the interior
    w = rng.dirichlet([1, 1, 1, 1], nsamp); smp = w @ V
    cands = []
    PA = np.array(pts)
    for t2 in T4:
        vol_t = abs(np.linalg.det(np.array([phys4(v) - phys4(T4[t2][0]) for v in T4[t2][1:]]))) / 6
        for g in range(120):
            offs = [RX[g] @ T4[t2][j] for j in range(4)]
            for p in pts:
                vs = [tuple(int(z) for z in (np.array(p) + o)) for o in offs]
                if all(v in idx for v in vs):
                    Vt = np.array([phys4(v) for v in vs]); dv = abs(np.linalg.det(Vt[1:] - Vt[0])) / 6
                    if dv < 1e-9: continue
                    cov = frozenset(np.where((bary(smp, Vt) > 1e-9).all(1))[0].tolist())
                    cands.append((t2, g, p, cov, dv, frozenset(vs)))
    # deduplicate by vertex set (a tile and its symmetric images coincide)
    uniq = {}
    for c in cands: uniq.setdefault((c[0], c[5]), c)
    cands = list(uniq.values()); cands = [c for c in cands if len(c[3]) > 0]
    if verbose: print(name, "candidate tiles", len(cands), flush=True)
    return V4, V, smp, cands

MROW = {"K": {"K": 1, "B": 1, "C": 0, "A": 0}, "B": {"K": 4, "B": 2, "C": 1, "A": 0}, "C": {"K": 2, "B": 0, "C": 2, "A": 1}, "A": {"K": 6, "B": 3, "C": 2, "A": 0}}
def solve(name, cap=50, **kw):
    V4, V, smp, cands = dissect(name, **kw)
    n = len(smp); full = frozenset(range(n)); by_pt = [[] for _ in range(n)]
    for ci, c in enumerate(cands):
        for s in c[3]: by_pt[s].append(ci)
    target = abs(np.linalg.det(V[1:] - V[0])) / 6; sols = []; nodes = [0]
    uncovered_ok = [i for i in range(n) if by_pt[i]]
    def rec(unc, chosen, vol):
        if len(sols) >= cap or nodes[0] > 2_000_000: return
        nodes[0] += 1
        if not unc:
            if abs(vol - target) < 1e-7: sols.append(list(chosen))
            return
        if vol > target + 1e-7: return
        s = min(unc, key=lambda i: sum(1 for ci in by_pt[i] if cands[ci][3] <= unc))
        for ci in by_pt[s]:
            c = cands[ci]
            if c[3] <= unc:
                chosen.append(ci); rec(unc - c[3], chosen, vol + c[4]); chosen.pop()
    rec(frozenset(uncovered_ok), [], 0.0)
    out = []
    for sol in sols:
        cnt = {k: 0 for k in "KBCA"}
        for ci in sol: cnt[cands[ci][0]] += 1
        out.append((cnt, [(cands[ci][0], cands[ci][1], cands[ci][2]) for ci in sol]))
    return V4, out, nodes[0]
if __name__ == "__main__":
    res = {}
    for name in "KBCA":
        t0 = time.time(); V4, out, nodes = solve(name)
        match = [o for o in out if o[0] == MROW[name]]
        print(name, "solutions found", len(out), "with the matrix counts", len(match), "nodes", nodes, "%.0fs" % (time.time() - t0), [o[0] for o in out[:4]], flush=True)
        res[name] = [dict(counts=o[0], tiles=[(t, g, list(map(int, p))) for t, g, p in o[1]]) for o in match]
    json.dump(res, open("dissections.json", "w"))
