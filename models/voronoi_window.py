import numpy as np
from scipy.spatial import ConvexHull

_HERE = os.path.dirname(os.path.realpath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

import e8_shells as es  # noqa: E402
import fibre_window as fw  # noqa: E402
import hopf_shells as hs  # noqa: E402
from hopf_shells import hurwitz_units, qmul  # noqa: E402

_C = {}


def roots():
    return hs.e8_roots()


def _orbit(seed, S):
    """Closure of the points ``seed`` (k, 8) under the reflections in the rows of S."""
    key = lambda X: [tuple(r) for r in (np.round(X * 1e5).astype(np.int64) + 0)]
    seen = {}
    for k, p in zip(key(seed), seed):
        seen[k] = p
    frontier = np.array(list(seen.values()))
    while len(frontier):
        new = []
        for a in S:
            img = frontier - 2.0 * np.outer(frontier @ a, a) / (a @ a)
            for k, p in zip(key(img), img):
                if k not in seen:
                    seen[k] = p
                    new.append(p)
        frontier = np.array(new)
    return np.array(list(seen.values()))


def voronoi_vertices():
    """(vertices (19440, 8), norm^2 list) of the Voronoi cell of E8 (cached)."""
    if "vv" in _C:
        return _C["vv"]
    R = roots()
    S = hs.e8_simple_roots(R)
    funct = np.random.default_rng(5).normal(size=8)
    theta = R[np.argmax(R @ funct)]                       # highest root
    m = np.linalg.solve(S.T, theta)                       # theta = sum m_i alpha_i
    omega = np.linalg.inv(S @ S.T) @ S                    # rows: omega_i with omega_i . alpha_j = delta_ij
    cand = omega / m[:, None]
    def is_vertex(c):
        t = R[np.abs(R @ c - 1) < 1e-9]
        return np.max(R @ c) <= 1 + 1e-9 and len(t) >= 8 and np.linalg.matrix_rank(t, tol=1e-9) == 8
    seeds = [c for c in cand if is_vertex(c)]
    _C["seed_norms"] = [round(float(c @ c), 6) for c in seeds]
    V = _orbit(np.array(seeds), S)
    _C["vv"] = V
    return V


def window_vertices_and_hull(kind="icosian"):
    """(hull, projected vertices) of W = proj_perp(Vor) for the splitting ``kind`` (cached)."""
    k = ("hull", kind)
    if k not in _C:
        V = voronoi_vertices()
        P = fw.split(V, kind)[1]
        P = np.unique(np.round(P, 9), axis=0)
        _C[k] = (ConvexHull(P), P)
    return _C[k]


def inside(Y, kind="icosian", tol=1e-7):
    """Boolean mask: the rows of Y (N, 4) lie in W."""
    h, _ = window_vertices_and_hull(kind)
    A, b = h.equations[:, :4].T, h.equations[:, 4]
    out = np.empty(len(Y), dtype=bool)
    for i in range(0, len(Y), 5000):                      # chunked: N x 2640 doubles would not fit in memory at once
        out[i:i + 5000] = np.all(Y[i:i + 5000] @ A + b <= tol, axis=1)
    return out


def accepted(nmax, kind="icosian"):
    """(points (M, 4), fibre labels (M,), mask over all vectors of shells 1..nmax)."""
    V, lab = fw.lattice(nmax)
    par, perp = fw.split(V, kind)
    mask = inside(perp, kind)
    return par[mask], lab[mask], mask, lab


def split_count(nmax, kind):
    """(number of split fibres, number of fibres) for the Voronoi window."""
    _, _, mask, lab = accepted(nmax, kind)
    u, inv = np.unique(lab, return_inverse=True)
    n_in = np.bincount(inv, weights=mask.astype(float))
    n_all = np.bincount(inv)
    return int(np.sum((n_in > 0) & (n_in < n_all))), len(u)


def radii(kind="icosian"):
    """(inradius, circumradius) of W about the origin."""
    h, P = window_vertices_and_hull(kind)
    d = -h.equations[:, 4] / np.linalg.norm(h.equations[:, :4], axis=1)
    return float(d.min()), float(np.linalg.norm(P, axis=1).max())


# ------------------------------------------------------------------------------------------------ tests

def run_tests(verbose=True, nmax=8):
    ok = True

    def check(name, cond, extra=""):
        nonlocal ok
        ok &= bool(cond)
        if verbose:
            print("  %-4s %s %s" % ("ok" if cond else "FAIL", name, extra))

    R = roots()
    V = voronoi_vertices()
    n2 = np.round((V ** 2).sum(1), 6)
    vals = {float(x): int((n2 == x).sum()) for x in set(n2)}
    check("Voronoi cell: 19440 vertices = 2160 (norm^2 1) + 17280 (norm^2 8/9)",
          len(V) == 19440 and vals == {1.0: 2160, round(8 / 9, 6): 17280}, str(vals))
    dots = V @ R.T
    tight = (np.abs(dots - 1) < 1e-9).sum(1)
    check("every vertex lies in the cell and is tight on at least 8 roots",
          dots.max() <= 1 + 1e-9 and tight.min() >= 8, "(tight on %d..%d roots)" % (tight.min(), tight.max()))
    rng = np.random.default_rng(0)
    pts = rng.normal(size=(2000, 8))
    pts *= (rng.random(2000) ** (1 / 8) * 1.2 / np.linalg.norm(pts, axis=1))[:, None]
    in_cell = (np.abs(pts @ R.T) <= 1 + 1e-12).all(1)
    lat, _ = fw.lattice(2)
    nearest = np.array([np.min(((p - np.vstack([np.zeros(8), lat])) ** 2).sum(1)) for p in pts[:300]])
    check("a point is in the cell iff the origin is its nearest lattice point (300 random points)",
          all((np.sqrt(nearest[i]) >= np.linalg.norm(pts[i]) - 1e-9) == in_cell[i] for i in range(300)))
    h, P = window_vertices_and_hull("icosian")
    check("icosian window: a 4D polytope with the origin inside",
          h.equations[:, 4].max() < 0, "(%d hull vertices, %d facets, volume %.4f)" % (len(h.vertices), len(h.equations), h.volume))
    # invariance under the fibre group
    T = hurwitz_units()
    inv_ok = True
    Vl, _ = fw.lattice(3)
    acc = inside(fw.split(Vl, "icosian")[1], "icosian")
    for t in T:
        img = np.hstack([qmul(Vl[:, :4], t), qmul(Vl[:, 4:], t)])
        acc_img = inside(fw.split(img, "icosian")[1], "icosian")
        inv_ok &= bool(np.array_equal(acc, acc_img))
    check("the window is invariant under the 24 fibre rotations: acceptance is unchanged by (a, b) -> (a l, b l), all 24 l", inv_ok)
    ns, nf = split_count(nmax, "icosian")
    _, _, mask, _ = accepted(nmax, "icosian")
    check("icosian Voronoi window: no fibre of shells 1..%d is split" % nmax, ns == 0 and 0 < mask.sum() < len(mask),
          "(%d of %d vectors accepted, %d fibres)" % (mask.sum(), len(mask), nf))
    ns_c, nf_c = split_count(nmax, "coxeter")
    check("negative control: the same construction in the Coxeter splitting splits fibres", ns_c > 0, "(%d of %d split)" % (ns_c, nf_c))
    r_in, r_out = radii("icosian")
    par, perp = fw.split(fw.lattice(nmax)[0], "icosian")
    rp = np.linalg.norm(perp, axis=1)
    m_ = inside(perp, "icosian")
    check("inradius %.4f and circumradius %.4f: below the first everything is accepted, above the second nothing" % (r_in, r_out),
          m_[rp < r_in - 1e-6].all() and not m_[rp > r_out + 1e-6].any() and r_in < r_out)
    # density
    pa = par[m_]
    vol = h.volume
    got, exp = 0, 0.0
    for rho in (3.6, 3.8):
        got += int(np.sum(np.linalg.norm(pa, axis=1) <= rho)) + 1
        exp += vol * fw.BALL4 * rho ** 4
    # completeness: needs all shells with 2n <= rho^2 + r_out^2
    check("accepted points with |par| <= rho match vol(W) vol(B4) rho^4 within 3 per cent (rho = 3.6, 3.8)",
          abs(got / exp - 1) < 0.03 and (3.8 ** 2 + r_out ** 2) / 2 <= nmax + 1e-9, "(ratio %.3f, need shells up to %.1f)" % (got / exp, (3.8 ** 2 + r_out ** 2) / 2))
    check("negative control: with half the window volume the prediction fails by more than 20 per cent", abs(got / (exp / 2) - 1) > 0.2)
    return ok


