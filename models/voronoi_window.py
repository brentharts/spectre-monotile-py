"""
voronoi_window.py - the Voronoi-cell window of E8 (our reading of the Elser-Sloane window) and the Hopf fibres.

What is built.  The E8 lattice (Hurwitz pairs, as in hopf_shells.py) has a Voronoi cell Vor = { x : |x . r| <= 1 for the 240 roots r }
with 240 facets.  For a splitting R^8 = parallel + perpendicular, the *Voronoi window* is the 4D polytope
        W = proj_perp(Vor),
and the point set is  L_W = { proj_par(v) : v in E8, proj_perp(v) in W }.  Because W is symmetric, v is accepted exactly when the
translated cell v + Vor meets the parallel space: L_W is the set of lattice points whose Voronoi cell the physical space cuts.
This is how I read the Elser-Sloane window (QUANTUM_GRAVITY.md, section 1); I did NOT have their paper, so this is a hypothesis about
*their* choice.  What is established here is a property of this window, whoever used it.

Construction.  The vertices of Vor are the W(E8) orbits of the alcove vertices omega_i / m_i that are holes (m_i the marks of the
highest root); they are generated by closing under the simple reflections.  W is the convex hull of their perpendicular projections.

Exact / checked (tests):
  1. Vor has 19440 vertices (2160 deep holes of norm^2 1 and 17280 shallow holes of norm^2 8/9) and every vertex is tight on at least 8 roots.
  2. For the icosian splitting, W is invariant under the 24 rotations x -> x l (l in 2T), i.e. under the group that moves along a fibre,
     because right multiplication by l is a lattice automorphism that commutes with the splitting.  Hence L_W accepts or rejects every
     fibre whole (checked on shells 1..8, 340 320 vectors).  This is a statement about the *group*, not about radii: it holds for
     every window invariant under that group.
  3. Negative control: for the Coxeter splitting of Quantum_Gravity_Lab, the same construction splits fibres.
  4. The window is bounded by two balls (inradius, circumradius) and contains the origin; the lattice vectors with perpendicular
     radius below the inradius are always accepted, those above the circumradius never.
Numeric: the number of accepted points with |par| <= rho matches vol(W) vol(B4) rho^4 (E8 covolume 1) within 1 per cent at rho = 3.6, 3.8;
  at small rho the count jumps (the parallel radii are discrete), so the match is poor there (ratios 0.9 to 1.7 at rho = 1.5 to 3.2).
Not claimed: that this is the Elser-Sloane set, that any structure here links to the Spectre or the Chair44.

    python3 models/voronoi_window.py                tests, then a figure
    python3 models/voronoi_window.py --tests-only
    python3 models/voronoi_window.py --no-show --save-dir figures
"""
