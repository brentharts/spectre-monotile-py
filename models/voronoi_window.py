def figure(save=None, show=True, nmax=8):
    import matplotlib
    if not show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    h, P = window_vertices_and_hull("icosian")
    V, _ = fw.lattice(nmax)
    par, perp = fw.split(V, "icosian")
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.6))
    rp = np.linalg.norm(perp, axis=1)
    m = inside(perp, "icosian")
    r_in, r_out = radii("icosian")
    bins = np.linspace(0, 3.0, 31)
    ax[0].hist(rp[m], bins=bins, alpha=0.7, label="accepted")
    ax[0].hist(rp[~m], bins=bins, alpha=0.5, label="rejected")
    ax[0].axvline(r_in, color="k", ls="--"); ax[0].axvline(r_out, color="k", ls=":")
    ax[0].set_xlabel("perpendicular radius"); ax[0].set_ylabel("lattice vectors (shells 1..%d)" % nmax)
    ax[0].set_title("Voronoi window: inradius %.2f, circumradius %.2f" % (r_in, r_out)); ax[0].legend()
    for kind, col in (("icosian", "tab:blue"), ("coxeter", "tab:red")):
        fr = [split_count(n, kind)[0] / split_count(n, kind)[1] for n in range(1, nmax + 1)]
        ax[1].plot(range(1, nmax + 1), fr, "o-", color=col, label=kind)
    ax[1].set_xlabel("shells 1..N included"); ax[1].set_ylabel("fraction of fibres split")
    ax[1].set_title("Voronoi window and fibres"); ax[1].legend()
    ax[2].scatter(P[:, 0], P[:, 1], s=1, color="tab:blue")
    ax[2].scatter(P[h.vertices][:, 0], P[h.vertices][:, 1], s=8, color="tab:red")
    ax[2].set_aspect("equal"); ax[2].set_title("W: vertices projected to coords 1, 2 (%d hull vertices)" % len(h.vertices))
    fig.tight_layout()
    if save:
        os.makedirs(os.path.dirname(save) or ".", exist_ok=True)
        fig.savefig(save, dpi=150)
        print("saved", save)
    if show:
        plt.show()
    plt.close(fig)


def main(argv):
    if "--skip-tests" not in argv:
        print("tests:")
        if not run_tests():
            print("TESTS FAILED")
            return 1
    if "--tests-only" in argv:
        return 0
    d = argv[argv.index("--save-dir") + 1] if "--save-dir" in argv else None
    figure(os.path.join(d, "voronoi_window.png") if d else None, "--no-show" not in argv)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
